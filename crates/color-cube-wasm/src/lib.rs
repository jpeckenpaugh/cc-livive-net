//! Typed `wasm-bindgen` surface over the core and the Thistlethwaite solver
//! (D004, D026-D028).
//!
//! The module is stateless: every export takes facelets or moves and returns a
//! new value. Both table bundles are embedded at compile time (D027); there is
//! no runtime fetch and Kociemba is not linked into the browser build.
//!
//! Fallible exports return `Result<_, JsValue>`, which `wasm-bindgen` turns
//! into a thrown JavaScript `Error`. The one non-error empty result is
//! [`solve`] on an already-solved cube, which returns `""`; the matching
//! [`solve_report`] returns an empty report (D028).
//!
//! The seed argument is a `u32` and is zero-extended to the core's `u64`
//! (D028): a stable, BigInt-free 32-bit subset of the frozen `from_seed`
//! contract.

use std::fmt::Write as _;
use std::sync::OnceLock;

use color_cube::{
    parse_moves, write_singmaster, Color, Cube, Move, N_COLORS, N_FACELETS, N_MOVES, N_OBSERVATIONS,
};
use color_cube_solver::coords;
use color_cube_solver::{Limits, SolveError, Solver, Thistlethwaite};
use wasm_bindgen::prelude::*;

/// Move-table bundle generated by `gen-tables` and embedded at build time.
const MOVE_TABLES: &[u8] = include_bytes!("../../../tables/cc-tables-v1.bin");
/// Thistlethwaite distance bundle generated by `gen-tables`.
const DISTANCE_TABLES: &[u8] = include_bytes!("../../../tables/cc-thistlethwaite-v1.bin");

/// Number of seeds exercised by [`check`].
const CONFORMANCE_SEEDS: u64 = 32;

fn js_error(message: impl AsRef<str>) -> JsValue {
    js_sys::Error::new(message.as_ref()).into()
}

fn embedded_solver() -> Result<&'static Thistlethwaite, String> {
    static SOLVER: OnceLock<Result<Thistlethwaite, String>> = OnceLock::new();
    SOLVER
        .get_or_init(|| {
            Thistlethwaite::from_encoded(MOVE_TABLES, DISTANCE_TABLES)
                .map_err(|error| error.to_string())
        })
        .as_ref()
        .map_err(Clone::clone)
}

/// Decodes 54 colour indices into a legal cube.
fn decode_facelets(facelets: &[u8]) -> Result<Cube, String> {
    if facelets.len() != N_FACELETS {
        return Err(format!(
            "facelets must contain {N_FACELETS} colour indices, got {}",
            facelets.len()
        ));
    }
    let mut colors = [Color::U; N_FACELETS];
    for (slot, &raw) in facelets.iter().enumerate() {
        let index = usize::from(raw);
        if index >= N_COLORS {
            return Err(format!(
                "facelet {slot} has colour index {raw}; expected 0..{N_COLORS}"
            ));
        }
        colors[slot] = Color::ALL[index];
    }
    Cube::from_facelets(&colors).map_err(|error| format!("invalid cube: {error}"))
}

fn color_indices(cube: &Cube) -> Vec<u8> {
    cube.facelets()
        .iter()
        .map(|color| color.index() as u8)
        .collect()
}

fn moves_to_string(moves: &[Move]) -> String {
    let mut buffer = [0u8; 256];
    let length = write_singmaster(moves, &mut buffer).unwrap_or(0);
    String::from_utf8_lossy(&buffer[..length]).into_owned()
}

fn parse_facelets(facelets: &[u8]) -> Result<Cube, JsValue> {
    decode_facelets(facelets).map_err(js_error)
}

/// A solved report used for an already-solved input (D028).
fn solved_report() -> SolveReport {
    SolveReport {
        moves: String::new(),
        phase1: 0,
        phase2: 0,
        elapsed_ms: 0.0,
        solver: String::from("thistlethwaite"),
    }
}

/// Scrambles a cube with the pruned 25-move walk for `seed`.
///
/// The `u32` seed is zero-extended to the core's `u64` seed space (D028).
#[wasm_bindgen]
#[must_use]
pub fn scramble(seed: u32) -> String {
    let (_, scramble) = Cube::from_scramble(u64::from(seed), 25);
    moves_to_string(scramble.as_slice())
}

/// Solves a cube given as 54 colour indices; returns `""` when already solved.
///
/// # Errors
///
/// Throws a JavaScript `Error` for malformed facelets or a solver failure.
#[wasm_bindgen]
pub fn solve(facelets: &[u8]) -> Result<String, JsValue> {
    let cube = parse_facelets(facelets)?;
    if cube.is_solved() {
        return Ok(String::new());
    }
    let solution = embedded_solver()
        .map_err(js_error)?
        .solve(&cube, Limits::default())
        .map_err(|error| js_error(error.to_string()))?;
    Ok(moves_to_string(&solution.moves))
}

/// Solves a cube and returns the moves plus per-phase counts and timing.
///
/// An already-solved cube yields an empty successful report (D028).
///
/// # Errors
///
/// Throws a JavaScript `Error` for malformed facelets or a solver failure.
#[wasm_bindgen]
pub fn solve_report(facelets: &[u8]) -> Result<SolveReport, JsValue> {
    let cube = parse_facelets(facelets)?;
    if cube.is_solved() {
        return Ok(solved_report());
    }
    let solver = embedded_solver().map_err(js_error)?;
    let started = js_sys::Date::now();
    let result = solver.solve_with_stats(&cube, Limits::default());
    let elapsed_ms = (js_sys::Date::now() - started).max(0.0);
    let (solution, phases, _nodes) = result.map_err(|error| js_error(error.to_string()))?;
    Ok(SolveReport {
        moves: moves_to_string(&solution.moves),
        phase1: phases[0] as u32,
        phase2: phases[1] as u32,
        elapsed_ms,
        solver: String::from("thistlethwaite"),
    })
}

/// Read-only projection of the core cubie state for the browser inspector.
///
/// Every getter returns an owned copy: the wasm boundary never aliases the
/// core arrays. The browser treats this as a derived view of its one facelet
/// snapshot, not as a second state store.
///
/// `ep8_rank` and `sp_rank` exist only on `G1` states (D018). Outside `G1`
/// they are `None`, which `wasm-bindgen` surfaces as JavaScript `undefined`.
/// Compare with `value === undefined`, never truthiness: rank `0` is valid.
#[wasm_bindgen]
#[derive(Debug)]
pub struct CubeView {
    cp: [u8; 8],
    co: [u8; 8],
    ep: [u8; 12],
    eo: [u8; 12],
    twist: u16,
    flip: u16,
    slice: u16,
    cp_rank: u16,
    ep8_rank: Option<u16>,
    sp_rank: Option<u8>,
    valid: bool,
    solved: bool,
    cube_bytes: u32,
}

#[wasm_bindgen]
impl CubeView {
    /// Piece index at each of the eight corner positions.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn cp(&self) -> Vec<u8> {
        self.cp.to_vec()
    }

    /// Corner orientation at each position, `0..3`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn co(&self) -> Vec<u8> {
        self.co.to_vec()
    }

    /// Piece index at each of the twelve edge positions.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn ep(&self) -> Vec<u8> {
        self.ep.to_vec()
    }

    /// Edge orientation at each position, `0..2`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn eo(&self) -> Vec<u8> {
        self.eo.to_vec()
    }

    /// Seven-term corner-twist coordinate, `0..2187`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn twist(&self) -> u16 {
        self.twist
    }

    /// Eleven-term edge-flip coordinate, `0..2048`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn flip(&self) -> u16 {
        self.flip
    }

    /// Middle-slice combination coordinate, `0..495`; `494` is a clean slice.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn slice(&self) -> u16 {
        self.slice
    }

    /// Lehmer rank of the corner permutation, `0..40320`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn cp_rank(&self) -> u16 {
        self.cp_rank
    }

    /// Rank of the eight U/D edges, `0..40320`; `undefined` outside `G1`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn ep8_rank(&self) -> Option<u16> {
        self.ep8_rank
    }

    /// Rank of the four middle edges, `0..24`; `undefined` outside `G1`.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn sp_rank(&self) -> Option<u8> {
        self.sp_rank
    }

    /// Whether the decoded state satisfies every cube invariant.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn is_valid(&self) -> bool {
        self.valid
    }

    /// Whether the state is the identity cube.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn is_solved(&self) -> bool {
        self.solved
    }

    /// `core::mem::size_of::<Cube>()` for the target that built this module.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn cube_bytes(&self) -> u32 {
        self.cube_bytes
    }
}

/// Decodes 54 colour indices and returns the inspector view of the state.
///
/// `ep8_rank` and `sp_rank` are `undefined` outside `G1` (D018).
///
/// # Errors
///
/// Throws a JavaScript `Error` for malformed facelets, matching [`solve`].
#[wasm_bindgen]
pub fn cube_view(facelets: &[u8]) -> Result<CubeView, JsValue> {
    let cube = parse_facelets(facelets)?;
    let g1 = coords::is_g1(&cube);
    Ok(CubeView {
        cp: cube.cp,
        co: cube.co,
        ep: cube.ep,
        eo: cube.eo,
        twist: coords::twist(&cube),
        flip: coords::flip(&cube),
        slice: coords::slice(&cube),
        cp_rank: coords::cp_rank(&cube),
        ep8_rank: g1.then(|| coords::ep8_rank(&cube)),
        sp_rank: g1.then(|| coords::sp_rank(&cube) as u8),
        valid: cube.is_valid(),
        solved: cube.is_solved(),
        cube_bytes: core::mem::size_of::<Cube>() as u32,
    })
}

/// Returns the embedded structure metadata used by the Rust types tab.
///
/// The JSON is the same `web/structures.json` that `scripts/check-structures.mjs`
/// verifies against the source, so the page and the drift guard cannot disagree.
#[wasm_bindgen]
#[must_use]
pub fn data_structure_meta() -> String {
    include_str!("../../../web/structures.json").to_string()
}

/// Applies a Singmaster move string to the solved cube and returns facelets.
///
/// # Errors
///
/// Throws a JavaScript `Error` for unknown or too many move tokens.
#[wasm_bindgen]
pub fn facelets_after(moves: &str) -> Result<Vec<u8>, JsValue> {
    let parsed = parse_moves(moves).map_err(|error| js_error(format!("invalid moves: {error}")))?;
    let mut cube = Cube::SOLVED;
    cube.apply_all(parsed.as_slice());
    Ok(color_indices(&cube))
}

/// Applies a move string to an existing facelet array and returns the result.
///
/// This keeps the browser stateless: the UI holds only the last facelet
/// snapshot and passes it back with the next move.
///
/// # Errors
///
/// Throws a JavaScript `Error` for malformed facelets, unknown moves, or more
/// than 64 moves in one call.
#[wasm_bindgen]
pub fn apply_facelets(facelets: &[u8], moves: &str) -> Result<Vec<u8>, JsValue> {
    let mut cube = parse_facelets(facelets)?;
    let parsed = parse_moves(moves).map_err(|error| js_error(format!("invalid moves: {error}")))?;
    cube.apply_all(parsed.as_slice());
    Ok(color_indices(&cube))
}

/// Returns the canonical 324-float one-hot observation (D006).
///
/// # Errors
///
/// Throws a JavaScript `Error` for malformed facelets.
#[wasm_bindgen]
pub fn observe(facelets: &[u8]) -> Result<Vec<f32>, JsValue> {
    let cube = parse_facelets(facelets)?;
    let mut out = [0.0f32; N_OBSERVATIONS];
    cube.write_observation(&mut out);
    Ok(out.to_vec())
}

/// Returns the unrestricted action mask: 18 ones.
#[wasm_bindgen]
#[must_use]
pub fn action_mask() -> Vec<f32> {
    let mut out = [0.0f32; N_MOVES];
    Cube::SOLVED.write_action_mask(&mut out);
    out.to_vec()
}

/// Returns the canonical action mask after `last` (D014).
///
/// # Errors
///
/// Throws a JavaScript `Error` when `last` is not a move index in `0..18`.
#[wasm_bindgen]
pub fn canonical_mask(last: Option<u8>) -> Result<Vec<f32>, JsValue> {
    let last = match last {
        None => None,
        Some(index) => Some(
            Move::from_index(index)
                .ok_or_else(|| js_error(format!("move index {index} is not in 0..18")))?,
        ),
    };
    let mut out = [0.0f32; N_MOVES];
    Cube::SOLVED.write_canonical_mask(last, &mut out);
    Ok(out.to_vec())
}

/// Returns the 54 facelets of the solved cube as colour indices.
#[wasm_bindgen]
#[must_use]
pub fn solved_facelets() -> Vec<u8> {
    color_indices(&Cube::SOLVED)
}

/// Returns the 18 move labels in action order.
#[wasm_bindgen]
#[must_use]
pub fn move_names() -> Vec<String> {
    Move::ALL
        .iter()
        .map(|mv| mv.to_singmaster().to_string())
        .collect()
}

/// Runs a compact smoke conformance suite inside the wasm module (D028).
///
/// The suite is a representative subset, not the Rust test suite: 32 seeds,
/// core move/notation/observation invariants, and solve/replay for the same 32
/// seeds. It deliberately excludes table generation and the exhaustive `G3`
/// diameter check, both of which are far outside the browser budget.
#[wasm_bindgen]
#[must_use]
pub fn check() -> ConformanceReport {
    let mut checks = Checks::default();

    let solver = embedded_solver();
    checks.record(
        "embedded table bundles",
        solver.as_ref().map(|_| ()).map_err(Clone::clone),
    );

    checks.record(
        "solved facelets",
        Cube::from_facelets(&Cube::SOLVED.facelets())
            .map_err(|error| error.to_string())
            .and_then(|cube| {
                if cube.is_solved() {
                    Ok(())
                } else {
                    Err(String::from("solved facelets decoded to a non-solved cube"))
                }
            }),
    );

    checks.record("move algebra", {
        let mut failure = None;
        for mv in Move::ALL {
            let mut fourth = Cube::SOLVED;
            for _ in 0..4 {
                fourth.apply(mv);
            }
            if !fourth.is_solved() {
                failure = Some(format!("{}^4 is not the identity", mv.to_singmaster()));
                break;
            }
            let mut cancelled = Cube::SOLVED;
            cancelled.apply(mv);
            cancelled.apply(mv.inverse());
            if !cancelled.is_solved() {
                failure = Some(format!(
                    "{} {} is not the identity",
                    mv.to_singmaster(),
                    mv.inverse().to_singmaster()
                ));
                break;
            }
        }
        failure.map_or(Ok(()), Err)
    });

    checks.record("notation round-trip", {
        let mut buffer = [0u8; 256];
        write_singmaster(&Move::ALL, &mut buffer)
            .map_err(|error| error.to_string())
            .and_then(|length| {
                let text =
                    std::str::from_utf8(&buffer[..length]).map_err(|error| error.to_string())?;
                let parsed = parse_moves(text).map_err(|error| error.to_string())?;
                if parsed.as_slice() == Move::ALL.as_slice() {
                    Ok(())
                } else {
                    Err(String::from("parsed moves differ from the input"))
                }
            })
    });

    let seeds: Vec<u64> = (0..CONFORMANCE_SEEDS).collect();
    checks.record("32 seeded cubes", {
        let mut failure = None;
        for &seed in &seeds {
            let cube = Cube::from_seed(seed);
            if !cube.is_valid() || cube.is_solved() {
                failure = Some(format!("seed {seed} is not a valid scrambled cube"));
                break;
            }
        }
        failure.map_or(Ok(()), Err)
    });

    checks.record("facelet round-trip", {
        let mut failure = None;
        for &seed in &seeds {
            let cube = Cube::from_seed(seed);
            match Cube::from_facelets(&cube.facelets()) {
                Ok(decoded) if decoded == cube => {}
                Ok(_) => {
                    failure = Some(format!("seed {seed} facelets did not round-trip"));
                    break;
                }
                Err(error) => {
                    failure = Some(format!("seed {seed} facelets rejected: {error}"));
                    break;
                }
            }
        }
        failure.map_or(Ok(()), Err)
    });

    checks.record("observation shape", {
        let mut failure = None;
        for &seed in &seeds {
            let cube = Cube::from_seed(seed);
            let mut observation = [0.0f32; N_OBSERVATIONS];
            cube.write_observation(&mut observation);
            let ones = observation.iter().filter(|&&value| value == 1.0).count();
            let sum: f32 = observation.iter().sum();
            if ones != N_FACELETS || (sum - N_FACELETS as f32).abs() > f32::EPSILON {
                failure = Some(format!(
                    "seed {seed} observation has {ones} ones and sum {sum}"
                ));
                break;
            }
            for block in observation.as_chunks::<N_COLORS>().0 {
                if (block.iter().sum::<f32>() - 1.0).abs() > f32::EPSILON {
                    failure = Some(format!("seed {seed} has a non-one-hot facelet"));
                    break;
                }
            }
            if failure.is_some() {
                break;
            }
        }
        failure.map_or(Ok(()), Err)
    });

    checks.record("action masks", {
        let mut action = [0.0f32; N_MOVES];
        Cube::SOLVED.write_action_mask(&mut action);
        if action.iter().any(|&value| value != 1.0) {
            Err(String::from("default action mask is not all ones"))
        } else {
            let mut canonical = [0.0f32; N_MOVES];
            Cube::SOLVED.write_canonical_mask(None, &mut canonical);
            let unrestricted = canonical.iter().filter(|&&value| value == 1.0).count();
            Cube::SOLVED.write_canonical_mask(Some(Move(0)), &mut canonical);
            let after_u = canonical.iter().filter(|&&value| value == 1.0).count();
            if unrestricted == N_MOVES && after_u == N_MOVES - 3 {
                Ok(())
            } else {
                Err(format!(
                    "canonical mask has {unrestricted} then {after_u} ones"
                ))
            }
        }
    });

    if let Ok(solver) = solver {
        checks.record("solve and replay", {
            let mut failure = None;
            for &seed in &seeds {
                let cube = Cube::from_seed(seed);
                match solver.solve_with_phases(&cube) {
                    Ok((solution, phases)) => {
                        if solution.moves.len() > 45 {
                            failure = Some(format!("seed {seed} solution exceeds 45 moves"));
                            break;
                        }
                        if phases.iter().sum::<usize>() != solution.moves.len() {
                            failure = Some(format!("seed {seed} phase counts do not add up"));
                            break;
                        }
                        let mut replay = cube;
                        replay.apply_all(&solution.moves);
                        if !replay.is_solved() {
                            failure = Some(format!("seed {seed} solution did not replay"));
                            break;
                        }
                    }
                    Err(SolveError::AlreadySolved) => {
                        failure = Some(format!("seed {seed} was already solved"));
                        break;
                    }
                    Err(error) => {
                        failure = Some(format!("seed {seed} failed: {error}"));
                        break;
                    }
                }
            }
            failure.map_or(Ok(()), Err)
        });
    }

    checks.finish()
}

/// Result of [`solve_report`].
#[wasm_bindgen]
#[derive(Debug)]
pub struct SolveReport {
    moves: String,
    phase1: u32,
    phase2: u32,
    elapsed_ms: f64,
    solver: String,
}

#[wasm_bindgen]
impl SolveReport {
    /// The Singmaster solution; empty when the input was already solved.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn moves(&self) -> String {
        self.moves.clone()
    }

    /// Move count for Thistlethwaite phase 1 (at most 7).
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn phase1(&self) -> u32 {
        self.phase1
    }

    /// Move count for Thistlethwaite phase 2 (at most 10).
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn phase2(&self) -> u32 {
        self.phase2
    }

    /// Wall-clock solve time measured with `Date.now()` (D028).
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn elapsed_ms(&self) -> f64 {
        self.elapsed_ms
    }

    /// Solver name; always `"thistlethwaite"` in the browser build.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn solver(&self) -> String {
        self.solver.clone()
    }
}

/// Result of [`check`].
#[wasm_bindgen]
#[derive(Debug)]
pub struct ConformanceReport {
    passed: u32,
    failed: u32,
    details: String,
}

#[wasm_bindgen]
impl ConformanceReport {
    /// Number of checks that passed.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn passed(&self) -> u32 {
        self.passed
    }

    /// Number of checks that failed.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn failed(&self) -> u32 {
        self.failed
    }

    /// Multi-line `ok`/`FAIL` summary.
    #[wasm_bindgen(getter)]
    #[must_use]
    pub fn details(&self) -> String {
        self.details.clone()
    }
}

#[derive(Default)]
struct Checks {
    passed: u32,
    failed: u32,
    details: String,
}

impl Checks {
    fn record(&mut self, name: &str, result: Result<(), String>) {
        match result {
            Ok(()) => {
                self.passed += 1;
                let _ = writeln!(self.details, "ok   {name}");
            }
            Err(message) => {
                self.failed += 1;
                let _ = writeln!(self.details, "FAIL {name}: {message}");
            }
        }
    }

    fn finish(self) -> ConformanceReport {
        ConformanceReport {
            passed: self.passed,
            failed: self.failed,
            details: self.details,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::decode_facelets;
    use color_cube::{Color, Cube, Move, Scramble};

    #[test]
    fn structure_sizes_match_metadata() {
        // Mirrors the hard-coded table in scripts/check-structures.mjs. A change
        // here must update web/structures.json and the guard together.
        assert_eq!(core::mem::size_of::<Cube>(), 40);
        assert_eq!(core::mem::size_of::<Move>(), 1);
        assert_eq!(core::mem::size_of::<Color>(), 1);
        assert_eq!(core::mem::size_of::<Scramble>(), 33);
    }

    #[test]
    fn rejects_wrong_length() {
        assert!(decode_facelets(&[0u8; 53]).unwrap_err().contains("54"));
        assert!(decode_facelets(&[]).unwrap_err().contains("54"));
    }

    #[test]
    fn rejects_out_of_range_colour() {
        let mut facelets = crate::solved_facelets();
        facelets[0] = 6;
        assert!(decode_facelets(&facelets)
            .unwrap_err()
            .contains("colour index 6"));
    }

    #[test]
    fn rejects_bad_centres() {
        let mut facelets = crate::solved_facelets();
        facelets[4] = 1;
        assert!(decode_facelets(&facelets).is_err());
    }

    #[test]
    fn accepts_solved() {
        let cube = decode_facelets(&crate::solved_facelets()).expect("solved decodes");
        assert!(cube.is_solved());
    }
}
